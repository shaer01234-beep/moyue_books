// 协议文本与同意状态（localStorage 持久化）。
// 升级协议时递增 AGREEMENT_VERSION，已同意旧版本的用户会再次看到新协议。

export const AGREEMENT_VERSION = '1'

const STORAGE_KEY = 'moyue.agreement'

// 是否已同意当前版本协议
export function hasAgreedAgreement() {
  try {
    return localStorage.getItem(STORAGE_KEY) === AGREEMENT_VERSION
  } catch {
    return false
  }
}

// 标记已同意当前版本
export function markAgreementAgreed() {
  try {
    localStorage.setItem(STORAGE_KEY, AGREEMENT_VERSION)
  } catch {
    /* 忽略 */
  }
}

